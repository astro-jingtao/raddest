def construct_trainer(log_likelihood, step):

    def trainer(params,
                x_ext,
                y_ext,
                w,
                lr=1e-3,
                n_step=10000,
                atol=1e-3,
                rtol=1e-3,
                verbose=False):
        params_old = params

        for i in range(n_step):
            params = step(params, x_ext, y_ext, w, lr)

            if (i % 1000 == 0):
                if verbose:
                    print(i, *params, log_likelihood(params, x_ext, y_ext, w))
                if (jnp.allclose(jnp.array(params),
                                 jnp.array(params_old),
                                 atol=atol,
                                 rtol=rtol)) and (i > 0):
                    if verbose:
                        print(f'converged, so stop with {i} iterations')
                    break
                params_old = params
        return params

    return trainer


def construct_likelihood(p_cond):
    """
    construct likelihood function from conditional probability, p(y|x; params)
    
    Parameters
    ----------
    p_cond : callable
        ``(x, y, params) -> (N,)``, the conditional probability of y given
        x, ``p(y|x; params)``.

    Returns
    -------

    likelihood function, likelihod(params, x_ext, y_ext, w) -> (N, )
    """

    @jit
    def likelihhod(params, x_ext, y_ext, w):
        """
        params: k, b, sig
        x_ext, y_ext: (N, ), (N, ) the variable generated by GaussHermiteQuadrature
        w: (N, ) w = w_ghq * p(x, x_err) * p(y_err|y) * w_add
        """
        return jnp.sum(p_cond(x_ext, y_ext, params) * w, axis=1)

    return likelihhod


def construct_lognorm_likelihood(func):
    """
    construct lognorm likelihood function from conditional probability, N(log10y|func(log10x, params_func), sigma^2), params = params_func, sig
    """

    @jit
    def lognorm(x, y, params):
        # if x < 0 or y < 0 return 0, else gaussian(log10y - get_loc(log10x, params), get_scale(params))
        # params: (k, b, ...), sig
        return jnp.where((x < 0) | (y < 0), 0,
                         norm.pdf(jnp.log10(jnp.abs(y)),
                                  loc=func(jnp.log10(jnp.abs(x)), params[:-1]),
                                  scale=params[-1]))

    return construct_likelihood(lognorm)


def construct_linear_step(d_log_likelihood):

    @jit
    def step(params, x_ext, y_ext, w, lr=1e-3):
        # f = 0.5
        dparams = d_log_likelihood(params, x_ext, y_ext, w)[0]
        k, b, sig = params
        dk, db, dsig = dparams

        # dk = jnp.clip(dk, -jnp.abs(k) * f, jnp.abs(k) * f)
        # db = jnp.clip(db, -jnp.abs(b) * f, jnp.abs(b) * f)
        # dsig = jnp.clip(dsig, -jnp.abs(sig) * f, jnp.abs(sig) * f)

        k = jnp.clip(k + lr * dk, -1e2, 1e2)
        b = jnp.clip(b + lr * db, -1e2, 1e2)
        sig = jnp.clip(sig + lr * dsig, 1e-2, 1e2)
        return (k, b, sig)

    return step


def construct_linear_student_t_step(d_log_likelihood):

    @jit
    def step(params, x_ext, y_ext, w, lr=1e-3):
        dparams = d_log_likelihood(params, x_ext, y_ext, w)[0]
        k, b, df, sig = params
        dk, db, ddf, dsig = dparams
        k = jnp.clip(k + lr * dk, -1e2, 1e2)
        b = jnp.clip(b + lr * db, -1e2, 1e2)
        df = jnp.clip(df + lr * ddf, 1e-2, 1e2)
        sig = jnp.clip(sig + lr * dsig, 1e-2, 1e2)
        return (k, b, df, sig)

    return step


def construct_saturated_linear_step(d_log_likelihood):

    @jit
    def step(params, x_ext, y_ext, w, lr=1e-3):
        dparams = d_log_likelihood(params, x_ext, y_ext, w)[0]
        k, b, x0, x1, c0, c1, sig = params
        dk, db, dx0, dx1, dc0, dc1, dsig = jnp.nan_to_num(jnp.asarray(dparams),
                                                          nan=0.0)

        k = jnp.clip(k + lr * dk, -1e2, 1e2)
        b = jnp.clip(b + lr * db, -1e2, 1e2)
        x0 = jnp.clip(x0 + lr * dx0, -1e2, 1e2)
        x1 = jnp.clip(x1 + lr * dx1, -1e2, 1e2)
        c0 = jnp.clip(c0 + lr * dc0, -1e2, 1e2)
        c1 = jnp.clip(c1 + lr * dc1, -1e2, 1e2)

        sig = jnp.clip(sig + lr * dsig, 1e-2, 1e2)
        return (k, b, x0, x1, c0, c1, sig)

    return step


def parse_piecewise_params(n_piece, params):
    (b0, x0), others = params[:2], params[2:]
    k_lst = others[:n_piece]
    dx_lst = others[n_piece:]
    return b0, x0, k_lst, dx_lst


def flat_piecewise_params(b0, x0, k_lst, dx_lst):
    return (b0, x0, *k_lst, *dx_lst)


def project_to_hyperplane(y, A, b):
    """
    project y onto the hyperplane Ax+b
    """
    Ay_minus_b = A.dot(y) - b
    AAT = A.dot(A.T)
    lambda_ = jnp.linalg.pinv(AAT) @ Ay_minus_b
    projection = y - A.T.dot(lambda_)
    return projection


def piecewise_linear_step_factory(n_piece, A_eq=None, b_eq=None):

    if A_eq is not None:
        A_eq = jnp.asarray(A_eq)
        if b_eq is None:
            b_eq = jnp.zeros(A_eq.shape[0])
        else:
            b_eq = jnp.asarray(b_eq)
    else:
        if b_eq is not None:
            raise ValueError("b_eq should be None if A_eq is None")

    def constructor(d_log_likelihood):

        @jit
        def step(params, x_ext, y_ext, w, lr=1e-3):
            dparams = d_log_likelihood(params, x_ext, y_ext, w)[0]
            dparams = jnp.nan_to_num(jnp.asarray(dparams), nan=0.0)

            b0, x0, k_lst, dx_lst = parse_piecewise_params(
                n_piece, params[:-1])
            sig = params[-1]
            k_lst = jnp.asarray(k_lst)
            dx_lst = jnp.asarray(dx_lst)

            db0, dx0, dk_lst, ddx_lst = parse_piecewise_params(
                n_piece, dparams[:-1])
            dsig = dparams[-1]

            b0 = jnp.clip(b0 + lr * db0, -1e2, 1e2)
            x0 = jnp.clip(x0 + lr * dx0, -1e2, 1e2)
            k_lst = jnp.clip(k_lst + lr * dk_lst, -1e2, 1e2)
            dx_lst = jnp.clip(dx_lst + lr * ddx_lst, 1e-2, 1e2)
            sig = jnp.clip(sig + lr * dsig, 1e-2, 1e2)

            params_new = jnp.asarray(
                (*flat_piecewise_params(b0, x0, k_lst, dx_lst), sig))

            if A_eq is not None:
                params_new = project_to_hyperplane(params_new, A_eq, b_eq)

            return params_new

        return step

    return constructor


def construct_log_likelihood(likelihood):

    @jit
    def log_likelihood(params, x_ext, y_ext, w):
        return jnp.mean(jnp.log(likelihood(params, x_ext, y_ext, w) + 1e-10))

    d_log_likelihood = jit(grad(log_likelihood, argnums=(0, )))
    dd_log_likelihood = jit(
        jacrev(grad(log_likelihood, argnums=(0, )), argnums=(0, )))

    return log_likelihood, d_log_likelihood, dd_log_likelihood


def construct_generator_cond(func_x2y):

    def generator_cond(x, y_kdt, y_err_kdt, params, y_min=None, y_max=None):

        if y_min is None:
            y_min = y_kdt.min()
        if y_max is None:
            y_max = y_kdt.max()

        tree = KDTree(y_kdt.reshape(-1, 1))

        y_pred = func_x2y(x, params)
        y_pred = np.clip(y_pred, y_min, y_max)
        y_pred = np.nan_to_num(y_pred, nan=np.mean(y_kdt))  # nan to mean
        _, y_err_match_index = tree.query(y_pred.reshape(-1, 1))
        y_err_pred = y_err_kdt[y_err_match_index]
        y_obs_pred = y_pred + np.random.normal(scale=y_err_pred)

        return y_pred, y_err_pred, y_obs_pred

    return generator_cond


def construct_ks_compare(generator_cond, x_gen, x_obs_gen, y_kdt, y_err_kdt,
                         x_obs, y_obs):

    def ks_compare(*params):

        _, _, y_obs_gen = generator_cond(x_gen, y_kdt, y_err_kdt, params)

        return ks2d2s(x_obs_gen, y_obs_gen, x_obs, y_obs)

    return ks_compare
